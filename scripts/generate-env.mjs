#!/usr/bin/env node
/**
 * Generates src/environments/environment.generated.ts from .env files.
 *
 * Angular does not read .env files at build time, so this tiny prebuild step
 * keeps the runtime configuration in sync with the local environment.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(root, 'src/environments/environment.generated.ts');

function parseEnvFile(path) {
  if (!existsSync(path)) return {};

  const result = {};
  const contents = readFileSync(path, 'utf8').replace(/^\uFEFF/, '');

  for (const rawLine of contents.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;

    const separator = line.indexOf('=');
    if (separator === -1) continue;

    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    result[key] = value;
  }

  return result;
}

const fileEnv = {
  ...parseEnvFile(resolve(root, '.env')),
  ...parseEnvFile(resolve(root, '.env.local')),
  ...parseEnvFile(resolve(root, '.env.development')),
};

const supabaseUrl = (
  process.env['SUPABASE_URL'] ??
  fileEnv['SUPABASE_URL'] ??
  ''
).trim();
const supabaseAnonKey = (
  process.env['SUPABASE_ANON_KEY'] ??
  fileEnv['SUPABASE_ANON_KEY'] ??
  ''
).trim();

const isPlaceholder = (value) =>
  !value ||
  /your[-_]?project|example\.com|changeme|<.*>|placeholder/i.test(value);

const configured =
  !isPlaceholder(supabaseUrl) &&
  !isPlaceholder(supabaseAnonKey) &&
  /^https?:\/\//i.test(supabaseUrl);

const content = `/* AUTO-GENERATED by scripts/generate-env.mjs — do not edit manually. */
export const environment = {
  production: false,
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
  supabaseConfigured: ${configured},
} as const;
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, content, 'utf8');

if (configured) {
  console.log('✓ Supabase environment loaded from .env');
} else {
  console.log(
    'ℹ Supabase credentials not found — PulseChat will start in demo mode.\n' +
      '  Add SUPABASE_URL and SUPABASE_ANON_KEY to .env to use your project.',
  );
}
